"""Pick the home page's Featured Items and product-wall items from
products.json, download small copies of their photos into showcase/, and
write featured-data.js and showcase-data.js.

Usage (from the project folder, after build_products.py):
    python tools/build_home.py

Picks favour items with the most QC photos (a rough popularity signal) and
a recognisable style, spread across categories. To hand-pick instead, edit
the two .js files directly: each entry is {img, name, price, link}.
"""
import json, os, urllib.request, urllib.parse, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHOW = os.path.join(ROOT, 'showcase')
CNY_TO_USD = 0.163
INVITE_CODE = 'STEPAGENT'

FEATURED_CATS = {'jackets': 5, 'hoodies': 3, 'sweaters': 3, 'jeans': 2, 'sets': 2, 'pants': 1}
WALL_CATS = {'tops': 4, 'jackets': 4, 'hoodies': 2, 'sweaters': 2, 'jeans': 3, 'pants': 2,
             'shorts': 1, 'shoes': 2, 'bags': 1, 'hats': 1, 'jewelry': 1, 'sets': 1}


def load():
    items = json.load(open(os.path.join(ROOT, 'products.json'), encoding='utf-8'))['items']
    qc = json.load(open(os.path.join(ROOT, 'products-qc.json'), encoding='utf-8'))
    for i in items:
        i['qc'] = len(qc.get(i['id'], []))
        i['styled'] = any(t.startswith('style:') for t in i['t'])
    return items


def pick(items, quotas, taken):
    by = collections.defaultdict(list)
    for i in items:
        if i['id'] not in taken and i['c'] in quotas:
            by[i['c']].append(i)
    out = []
    for cat, n in quotas.items():
        ranked = sorted(by[cat], key=lambda i: (-i['styled'], -i['qc']))
        out += ranked[:n]
    # Interleave categories so neighbours differ.
    out.sort(key=lambda i: list(quotas).index(i['c']))
    rows = collections.defaultdict(list)
    for i in out:
        rows[i['c']].append(i)
    mixed = []
    while any(rows.values()):
        for cat in quotas:
            if rows[cat]:
                mixed.append(rows[cat].pop(0))
    taken.update(i['id'] for i in mixed)
    return mixed


def fetch_photo(url, dest, size):
    # Resized through the same image service the site uses for cards.
    src = 'https://wsrv.nl/?' + urllib.parse.urlencode(
        {'url': url, 'w': size, 'h': size, 'fit': 'cover', 'output': 'jpg', 'q': 80})
    req = urllib.request.Request(src, headers={'User-Agent': 'Mozilla/5.0'})
    with urllib.request.urlopen(req, timeout=60) as r, open(dest, 'wb') as f:
        f.write(r.read())


def entries(items, prefix, size, with_name):
    out = []
    for n, i in enumerate(items, 1):
        fname = f'{prefix}{n:02d}.jpg'
        fetch_photo(i['i'], os.path.join(SHOW, fname), size)
        e = {'img': f'showcase/{fname}'}
        if with_name:
            e['name'] = i['n']
        e['price'] = '$%.2f' % (i['y'] * CNY_TO_USD)
        e['link'] = f"https://boonbuy.com/product/2/{i['id']}?inviteCode={INVITE_CODE}"
        out.append(e)
    return out


def write_js(path, var, comment, data):
    with open(path, 'w', encoding='utf-8') as f:
        f.write(comment + f'window.{var} = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n')


def main():
    os.makedirs(SHOW, exist_ok=True)
    for f in os.listdir(SHOW):
        if f.endswith('.jpg'):
            os.remove(os.path.join(SHOW, f))
    items = load()
    taken = set()
    featured = pick(items, FEATURED_CATS, taken)
    wall = pick(items, WALL_CATS, taken)
    write_js(os.path.join(ROOT, 'featured-data.js'), 'FEATURED_ITEMS',
             '// Home page Featured Items carousel. Generated by tools/build_home.py;\n'
             '// photos are local copies so the carousel loads instantly.\n',
             entries(featured, 'fs', 360, True))
    write_js(os.path.join(ROOT, 'showcase-data.js'), 'SHOWCASE_ITEMS',
             '// Home page animated product wall. Generated by tools/build_home.py;\n'
             '// photos are local copies so the wall loads instantly.\n',
             entries(wall, 'sc', 320, False))
    print(f'{len(featured)} featured, {len(wall)} wall items')


if __name__ == '__main__':
    main()
